// Builds ./public (what the Worker serves as static files) from two sources:
//   ../github_pages   the customer's "check my fare" page (single source of truth)
//   ./monitor         the read-only panel
// and adds a generated config.js that points the customer page at this Worker.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const pages = join(root, "..", "github_pages");

if (!existsSync(join(pages, "index.html"))) {
  console.error(`No se encontró ${pages}: ejecuta este comando dentro de la carpeta completa del proyecto.`);
  process.exit(1);
}

rmSync(pub, { recursive: true, force: true });
mkdirSync(pub, { recursive: true });
for (const name of ["css", "js", "index.html"]) cpSync(join(pages, name), join(pub, name), { recursive: true });
cpSync(join(root, "monitor"), join(pub, "monitor"), { recursive: true });

// Point the customer page at this Worker instead of Google.
writeFileSync(join(pub, "js", "config.js"), '// generated by scripts/prepare-public.mjs\nwindow.PARKING_STATUS_ENDPOINT = "/api/session";\n');
const indexPath = join(pub, "index.html");
const html = readFileSync(indexPath, "utf8");
const tag = '<script src="js/status.js"></script>';
if (!html.includes(tag)) { console.error("github_pages/index.html ya no carga js/status.js: revisa prepare-public.mjs"); process.exit(1); }
writeFileSync(indexPath, html.replace(tag, '<script src="js/config.js"></script>\n' + tag));

// Browser hardening for every page. No inline scripts are used anywhere, so scripts are limited to this site.
writeFileSync(join(pub, "_headers"), `/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'
/monitor/*
  Cache-Control: no-store
  X-Robots-Tag: noindex, nofollow
`);
console.log("public/ listo");
